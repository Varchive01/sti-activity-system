// ── Ensure at least 50 Test Data Entries exist in `activities` (Panel 1 Requirement I.7) ──
function ensureMinimum50TestDataEntries(PDO $db, int $userId): int
{
    $currentCount = (int)$db->query("SELECT COUNT(*) FROM activities")->fetchColumn();
    if ($currentCount >= 50) {
        return $currentCount;
    }

    $needed = 50 - $currentCount;
    $sampleTemplates = [
        ['title' => 'STI IT Capstone & Software Engineering Symposium', 'theme' => 'Innovating Digital Solutions for Industry 5.0', 'venue' => 'STI AVR & Computer Lab 1', 'source' => 'faculty'],
        ['title' => 'THM Culinary Arts & Hospitality Excellence Expo', 'theme' => 'Global Standards in Tourism and Culinary Service', 'venue' => 'STI Function Hall', 'source' => 'faculty'],
        ['title' => 'General Education Research & Critical Thinking Colloquium', 'theme' => 'Empowering 21st Century Scholars', 'venue' => 'STI Main Auditorium', 'source' => 'faculty'],
        ['title' => 'SITE Cybersecurity & Ethical Hacking Workshop', 'theme' => 'Securing Campus and Cloud Infrastructure', 'venue' => 'Computer Laboratory 2', 'source' => 'student_org'],
        ['title' => 'CSG Campus Leadership & Student Governance Summit', 'theme' => 'Leading with Integrity and Service', 'venue' => 'STI Multi-Purpose Gymnasium', 'source' => 'student_org'],
    ];

    $insAct = $db->prepare("
        INSERT INTO activities (
            faculty_id, title, theme, event_date, end_date, start_time, end_time,
            venue, target_participants, source, status, general_objectives, specific_objectives, rationale, created_at
        ) VALUES (?, ?, ?, ?, ?, '09:00:00', '16:00:00', ?, ?, ?, 'completed', ?, ?, ?, NOW())
    ");

    for ($i = 1; $i <= $needed; $i++) {
        $tpl = $sampleTemplates[($i - 1) % count($sampleTemplates)];
        $seq = $currentCount + $i;
        $evDate = date('Y-m-d', strtotime("-" . ($i * 2) . " days"));
        $insAct->execute([
            387,
            $tpl['title'] . " (Batch #{$seq})",
            $tpl['theme'],
            $evDate,
            $evDate,
            $tpl['venue'],
            80 + ($i % 40),
            $tpl['source'],
            'To equip STI College Marikina students with practical, industry-aligned competencies.',
            "1. Demonstrate applied skills during the session.\n2. Achieve at least 85% participant satisfaction.",
            'AI-assisted institutional rationale aligned with departmental learning outcomes.'
        ]);
    }

    return (int)$db->query("SELECT COUNT(*) FROM activities")->fetchColumn();
}

