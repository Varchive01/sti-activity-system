if ($exportAction === 'export_sql') {
    if (function_exists('logSystemAuditEvent')) {
        logSystemAuditEvent('maintenance', 'database_backup_sql', 'Exported full SQL database backup archive');
    }
    if (ob_get_length()) ob_clean();
    $filename = 'sti_armes_backup_' . date('Ymd_His') . '.sql';
    header('Content-Type: application/sql; charset=UTF-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');

    echo "-- ======================================================================\n";
    echo "-- STI-ARMES DATABASE BACKUP & SYSTEM ARCHIVE\n";
    echo "-- Generated At: " . date('Y-m-d H:i:s') . "\n";
    echo "-- Generated By: " . ($user['name'] ?? 'Administrator') . " (" . ($user['role'] ?? 'dean') . ")\n";
    echo "-- ======================================================================\n\n";

    $tablesToBackup = ['academic_terms', 'authorized_organizations', 'academic_head_kpi_criteria', 'activities', 'post_event', 'approval_logs', 'system_audit_logs'];
    foreach ($tablesToBackup as $tbl) {
        try {
            $createRow = $db->query("SHOW CREATE TABLE {$tbl}")->fetch(PDO::FETCH_ASSOC);
            if ($createRow && isset($createRow['Create Table'])) {
                echo "-- Table structure for `{$tbl}`\n";
                echo "CREATE TABLE IF NOT EXISTS " . substr($createRow['Create Table'], 13) . ";\n\n";
            }
            $rows = $db->query("SELECT * FROM {$tbl} LIMIT 250")->fetchAll(PDO::FETCH_ASSOC);
            if (!empty($rows)) {
                echo "-- Dumping data for `{$tbl}` (" . count($rows) . " rows)\n";
                foreach ($rows as $r) {
                    $cols = array_map(fn($c) => "`{$c}`", array_keys($r));
                    $vals = array_map(fn($v) => $v === null ? 'NULL' : $db->quote((string)$v), array_values($r));
                    echo "INSERT IGNORE INTO `{$tbl}` (" . implode(', ', $cols) . ") VALUES (" . implode(', ', $vals) . ");\n";
                }
                echo "\n";
            }
        } catch (\Throwable $e) {}
    }
    exit;
} elseif ($exportAction === 'export_audit_csv') {
    if (ob_get_length()) ob_clean();
    header('Content-Type: text/csv; charset=UTF-8');
    header('Content-Disposition: attachment; filename="sti_armes_activity_trail_' . date('Ymd_His') . '.csv"');
    $out = fopen('php://output', 'w');
    fprintf($out, chr(0xEF) . chr(0xBB) . chr(0xBF));
    fputcsv($out, ['Timestamp', 'Category / Source', 'Actor Name', 'Role', 'Action', 'Details / Activity Trail']);
    $trailRows = $db->query("
        (SELECT created_at AS ts, CONCAT('Security / ', UPPER(event_type)) AS cat, user_name AS actor, user_role AS role, action, details FROM system_audit_logs)
        UNION ALL
        (SELECT al.acted_at AS ts, 'Approval Pipeline' AS cat, u.name AS actor, u.role AS role, al.action, CONCAT('Activity #', al.activity_id, ': ', COALESCE(al.notes, '')) AS details FROM approval_logs al LEFT JOIN users u ON al.reviewer_id = u.id)
        ORDER BY ts DESC LIMIT 300
    ")->fetchAll(PDO::FETCH_ASSOC);
    foreach ($trailRows as $tr) {
        fputcsv($out, [$tr['ts'], $tr['cat'], $tr['actor'], $tr['role'], $tr['action'], $tr['details']]);
    }
    fclose($out);
    exit;
}

